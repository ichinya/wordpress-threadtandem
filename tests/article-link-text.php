<?php
/** Announcement label coverage on the disposable integration installation. */
require __DIR__ . '/channel-sync.php';
add_filter( 'pre_http_request', 'treda_test_http', 10, 3 );
$original_site_language = get_option( 'WPLANG' );
update_option( 'WPLANG', 'ru_RU' );
$settings = Treda_Settings::get();
unset( $settings['article_link_text'] );
update_option( 'treda_settings', $settings );
treda_test_expect( Treda_Settings::article_link_text() === 'Читать статью', 'Russian site has a Russian article link without a plugin language pack' );
$input = Treda_Settings::get();
$input['article_link_text'] = '  Подробнее на сайте  ';
$saved = Treda_Settings::sanitize( $input );
treda_test_expect( $saved['article_link_text'] === 'Подробнее на сайте', 'Custom label is saved as trimmed plain text' );
$fingerprint = Treda_Settings::fingerprint();
update_option( 'treda_settings', $saved );
treda_test_expect( Treda_Settings::fingerprint() === $fingerprint && Treda_Settings::ready(), 'Changing label preserves verified connection and queued job identity' );
$input['article_link_text'] = '<script>alert(1)</script><b>Подробнее</b>';
$safe = Treda_Settings::sanitize( $input );
treda_test_expect( $safe['article_link_text'] === 'Подробнее', 'Label strips executable content and markup' );
$input['article_link_text'] = str_repeat( 'Я', 120 );
$safe = Treda_Settings::sanitize( $input );
treda_test_expect( $safe['article_link_text'] === str_repeat( 'Я', 100 ), 'Label length limit preserves multibyte characters' );
$input['article_link_text'] = array( 'malformed' );
$safe = Treda_Settings::sanitize( $input );
treda_test_expect( $safe['article_link_text'] === 'Подробнее на сайте', 'Malformed label does not overwrite the saved value' );
$input = Treda_Settings::get(); unset( $input['article_link_text'] );
$safe = Treda_Settings::sanitize( $input );
treda_test_expect( $safe['article_link_text'] === 'Подробнее на сайте', 'Older settings submissions retain the new label' );
$input['article_link_text'] = '   ';
update_option( 'treda_settings', Treda_Settings::sanitize( $input ) );
treda_test_expect( Treda_Settings::article_link_text() === 'Читать статью', 'Empty label falls back to the site-language default' );
$settings = Treda_Settings::get(); $settings['article_link_text'] = 'Первый текст'; update_option( 'treda_settings', $settings );
$id = wp_insert_post( array( 'post_title' => 'Article label queue test', 'post_excerpt' => 'Short excerpt', 'post_status' => 'publish' ) );
$settings['article_link_text'] = 'Открыть "статью" & подробности'; update_option( 'treda_settings', $settings );
$html = Treda_Publisher::text( get_post( $id ) );
treda_test_expect( strpos( $html, 'Открыть &quot;статью&quot; &amp; подробности</a>' ) !== false, 'Caption safely escapes quotes and ampersands' );
$before = count( treda_test_methods( 'sendMessage' ) );
treda_test_run();
$binding = get_post_meta( $id, '_treda_publication', true );
$sends = treda_test_methods( 'sendMessage' ); $last = end( $sends );
treda_test_expect( ! empty( $binding['message_id'] ) && count( $sends ) === $before + 1 && strpos( $last['params']['text'], 'Открыть &quot;статью&quot; &amp; подробности' ) !== false, 'Queued announcement uses the latest saved label at delivery time' );
$settings['article_link_text'] = 'Читать полностью'; update_option( 'treda_settings', $settings );
Treda_Queue::post( $id ); treda_test_run();
$edits = treda_test_methods( 'editMessageText' ); $last = end( $edits );
treda_test_expect( (int) $last['params']['message_id'] === (int) $binding['message_id'] && strpos( $last['params']['text'], '>Читать полностью</a>' ) !== false && count( treda_test_methods( 'sendMessage' ) ) === $before + 1, 'Label change edits the existing announcement instead of sending a duplicate' );
ob_start(); Treda_Admin::render(); $settings_html = ob_get_clean();
treda_test_expect( strpos( $settings_html, 'name="treda_settings[article_link_text]"' ) !== false && strpos( $settings_html, 'value="Читать полностью"' ) !== false, 'Settings form exposes and retains the editable label' );
update_option( 'WPLANG', $original_site_language );
remove_filter( 'pre_http_request', 'treda_test_http', 10 );
echo wp_json_encode( array( 'wordpress' => get_bloginfo( 'version' ), 'php' => PHP_VERSION, 'checks' => $treda_test_checks ), JSON_PRETTY_PRINT ) . PHP_EOL;
WP_CLI::success( count( $treda_test_checks ) . ' checks passed, including editable article links.' );
