<?php
/** Announcement label coverage on the disposable integration installation. */
require __DIR__ . '/channel-sync.php';
add_filter( 'pre_http_request', 'threadtandem_test_http', 10, 3 );
// Earlier failure scenarios intentionally leave blocked jobs; label tests use a fresh outbox.
$wpdb->query( $wpdb->prepare( 'DELETE FROM %i', ThreadTandem_Queue::table() ) );
$original_site_language = get_option( 'WPLANG' );
update_option( 'WPLANG', 'ru_RU' );
$settings = ThreadTandem_Settings::get();
unset( $settings['article_link_text'] );
update_option( 'threadtandem_settings', $settings );
threadtandem_test_expect( ThreadTandem_Settings::article_link_text() === 'Читать статью', 'Russian site has a Russian article link without a plugin language pack' );
$input = ThreadTandem_Settings::get();
$input['article_link_text'] = '  Подробнее на сайте  ';
$saved = ThreadTandem_Settings::sanitize( $input );
threadtandem_test_expect( $saved['article_link_text'] === 'Подробнее на сайте', 'Custom label is saved as trimmed plain text' );
$fingerprint = ThreadTandem_Settings::fingerprint();
update_option( 'threadtandem_settings', $saved );
threadtandem_test_expect( ThreadTandem_Settings::fingerprint() === $fingerprint && ThreadTandem_Settings::ready(), 'Changing label preserves verified connection and queued job identity' );
$input['article_link_text'] = '<script>alert(1)</script><b>Подробнее</b>';
$safe = ThreadTandem_Settings::sanitize( $input );
threadtandem_test_expect( $safe['article_link_text'] === 'Подробнее', 'Label strips executable content and markup' );
$input['article_link_text'] = str_repeat( 'Я', 120 );
$safe = ThreadTandem_Settings::sanitize( $input );
threadtandem_test_expect( $safe['article_link_text'] === str_repeat( 'Я', 100 ), 'Label length limit preserves multibyte characters' );
$input['article_link_text'] = array( 'malformed' );
$safe = ThreadTandem_Settings::sanitize( $input );
threadtandem_test_expect( $safe['article_link_text'] === 'Подробнее на сайте', 'Malformed label does not overwrite the saved value' );
$input = ThreadTandem_Settings::get(); unset( $input['article_link_text'] );
$safe = ThreadTandem_Settings::sanitize( $input );
threadtandem_test_expect( $safe['article_link_text'] === 'Подробнее на сайте', 'Older settings submissions retain the new label' );
$input['article_link_text'] = '   ';
update_option( 'threadtandem_settings', ThreadTandem_Settings::sanitize( $input ) );
threadtandem_test_expect( ThreadTandem_Settings::article_link_text() === 'Читать статью', 'Empty label falls back to the site-language default' );
$settings = ThreadTandem_Settings::get(); $settings['article_link_text'] = 'Первый текст'; update_option( 'threadtandem_settings', $settings );
$id = wp_insert_post( array( 'post_title' => 'Article label queue test', 'post_excerpt' => 'Short excerpt', 'post_status' => 'publish' ) );
$settings['article_link_text'] = 'Открыть "статью" & подробности'; update_option( 'threadtandem_settings', $settings );
$html = ThreadTandem_Publisher::text( get_post( $id ) );
threadtandem_test_expect( strpos( $html, 'Открыть "статью" & подробности' . "\n" . get_permalink( $id ) ) !== false && strpos( $html, '<a ' ) === false, 'Plain announcement preserves quotes, ampersands and a visible article URL' );
$before = count( threadtandem_test_methods( 'sendMessage' ) );
threadtandem_test_run();
$binding = get_post_meta( $id, '_threadtandem_publication', true );
$sends = threadtandem_test_methods( 'sendMessage' ); $last = end( $sends );
threadtandem_test_expect( ! empty( $binding['message_id'] ) && count( $sends ) === $before + 1 && strpos( $last['params']['text'], 'Открыть "статью" & подробности' ) !== false && ! isset( $last['params']['parse_mode'] ), 'Queued plain announcement uses the latest saved label at delivery time' );
$settings['article_link_text'] = 'Читать полностью'; update_option( 'threadtandem_settings', $settings );
ThreadTandem_Queue::post( $id ); threadtandem_test_run();
$edits = threadtandem_test_methods( 'editMessageText' ); $last = end( $edits );
threadtandem_test_expect( (int) $last['params']['message_id'] === (int) $binding['message_id'] && strpos( $last['params']['text'], "Читать полностью\n" . get_permalink( $id ) ) !== false && $last['params']['link_preview_options']['url'] === get_permalink( $id ) && count( threadtandem_test_methods( 'sendMessage' ) ) === $before + 1, 'Label change edits the existing text and preview instead of sending a duplicate' );
ob_start(); ThreadTandem_Admin::render(); $settings_html = ob_get_clean();
threadtandem_test_expect( strpos( $settings_html, 'name="threadtandem_settings[article_link_text]"' ) !== false && strpos( $settings_html, 'value="Читать полностью"' ) !== false, 'Settings form exposes and retains the editable label' );
update_option( 'WPLANG', $original_site_language );
remove_filter( 'pre_http_request', 'threadtandem_test_http', 10 );
echo wp_json_encode( array( 'wordpress' => get_bloginfo( 'version' ), 'php' => PHP_VERSION, 'checks' => $threadtandem_test_checks ), JSON_PRETTY_PRINT ) . PHP_EOL;
WP_CLI::success( count( $threadtandem_test_checks ) . ' checks passed, including editable article links.' );
